import argparse
import json
from pathlib import Path
import re
import sys
from typing import Any, Dict, Optional
import numpy as np
import pandas as pd
from occ.config import get_root_dir, load_config

T0 = 1_700_000_000.0  # Synthetic epoch
FAMILY_MAP = {
    "S1": "empty",
    "S2": "1p_seated",
    "S3": "3p_moving",
    "S4": "drill",
    "S5": "nearfar"
}

def parse_ns2_run(run_id: str, cfg: Optional[Dict[str, Any]] = None) -> Path:
    """Parse raw NS2 simulation trace into standard run directory."""
    if cfg is None:
        cfg = load_config()
    root = get_root_dir()
    sc = cfg["sim"]
    
    rssi_file = root / "ns2" / "out" / f"{run_id}.rssi"
    events_file = root / "ns2" / "out" / f"{run_id}.events.csv"
    
    if not rssi_file.is_file():
        raise FileNotFoundError(f"Missing NS2 RSSI trace: {rssi_file}")
    if not events_file.is_file():
        raise FileNotFoundError(f"Missing NS2 events file: {events_file}")
        
    out_dir = Path(sc["out_dir"])
    if not out_dir.is_absolute():
        out_dir = root / out_dir
    run_dir = out_dir / run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    
    # Read RSSI trace: t rx tx rssi
    d = pd.read_csv(rssi_file, sep=" ", names=["t", "rx", "tx", "rssi"], header=None)
    d["receiver_id"] = d["rx"].map({1: "R1", 2: "R2"})
    d = d.dropna(subset=["receiver_id"])
    
    if sc.get("quantize_dbm", True):
        d["rssi"] = np.rint(d["rssi"]).astype(int)
        
    rssi_out = pd.DataFrame({
        "t_host": (d["t"] + T0).round(3),
        "receiver_id": d["receiver_id"],
        "source_id": "TX1",
        "technology": "ns2_wifi",
        "channel": 6,
        "rssi_dbm": d["rssi"],
        "esp_ms": (d["t"] * 1000).astype(int)
    })
    rssi_out.to_csv(run_dir / "rssi.csv", index=False)
    
    # Read and shift events.csv
    ev = pd.read_csv(events_file)
    ev["t_host"] = (ev["t_host"] + T0).round(3)
    ev.to_csv(run_dir / "events.csv", index=False)
    
    # Parse scenario and seed from run_id
    match = re.match(r"SIM_(S\d)_seed(\d+)", run_id)
    if match:
        scn, seed_str = match.groups()
        seed = int(seed_str)
        family = FAMILY_MAP.get(scn, scn)
    else:
        scn = "S1"
        seed = 1
        family = "sim"
        
    meta = {
        "run_id": run_id,
        "day_id": "SIM",
        "date": "2026-10-12",
        "mode": "sim",
        "origin": "sim",
        "seed": seed,
        "scenario_family": family,
        "door_state": "closed",
        "furniture_config": "F1",
        "tx_device": "NS2_802.11",
        "sim_params": {**sc.get("channel", {}), **sc.get("body", {})},
        "notes": "Generated by NS2 simulation testbed"
    }
    with open(run_dir / "meta.json", "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)
        
    return run_dir

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Parse NS2 trace into standard dataset run folder")
    parser.add_argument("run_id", type=str, help="Run ID to parse (e.g., SIM_S2_seed01)")
    args = parser.parse_args()
    
    out = parse_ns2_run(args.run_id)
    print(f"[SUCCESS] Parsed NS2 trace {args.run_id} into {out}")
